import fs from 'node:fs/promises';
import { execSync } from 'node:child_process';
import { glob } from 'glob';

// CSS files to concatenate for the minimal build (for apps that run Tailwind):
// theme tokens, the vendored shadcn utilities/variants, Zen's adjustments to the
// shadcn components, then component CSS.
// Component stylesheets are discovered automatically so new components can't be
// forgotten. theme.css must come first: it holds the only @import.
// The list is resolved on every build, so a running --watch process picks up
// new files instead of silently rebuilding without them.
async function getCssFiles() {
  const componentCssFiles = (await glob('./src/components/*.css')).sort();
  return [
    './src/styles/theme.css',
    './src/styles/shadcn.css',
    './src/styles/zen.css',
    './src/styles/safelist.css',
    ...componentCssFiles,
  ];
}

const SAFELIST_FILE = './src/styles/safelist.css';
const BREAKPOINT_VARIANTS = '{,sm:,md:,lg:,xl:,2xl:}';

// Layout props accept responsive values ({ base: 'none', lg: 'flex' }), and mapResponsive
// builds the prefixed class (`lg:flex`) at runtime, so Tailwind never sees it in the source.
// Safelist every class in the lib/tailwind.ts maps at every breakpoint. Generated on each
// build so a new map value can't be forgotten.
async function buildSafelist() {
  const source = await fs.readFile('./src/components/lib/tailwind.ts', 'utf-8');
  const maps = [...source.matchAll(/^const (\w+Map): Record<string, string> = \{([\s\S]*?)^\};/gm)];
  const lines = maps.flatMap(([, name, body]) => {
    const classes = new Set(
      [...body.matchAll(/:\s*'([^']+)'/g)].flatMap(([, value]) => value.split(/\s+/)),
    );
    return classes.size
      ? [`/* ${name} */`, `@source inline("${BREAKPOINT_VARIANTS}{${[...classes].join(',')}}");`]
      : [];
  });

  if (maps.length === 0) {
    throw new Error('No class maps found in src/components/lib/tailwind.ts');
  }

  const output = [
    '/* Generated by css.mjs from src/components/lib/tailwind.ts. Do not edit. */',
    '/* Responsive classes built at runtime by mapResponsive, safelisted at every breakpoint. */',
    ...lines,
    '',
  ].join('\n');

  await fs.writeFile(SAFELIST_FILE, output, 'utf-8');
}

async function buildMinimalCSS() {
  const cssFiles = await getCssFiles();
  const contents = await Promise.all(
    cssFiles.map(async file => {
      const content = await fs.readFile(file, 'utf-8');
      return `/* ${file} */\n${content}`;
    })
  );

  const output = contents.join('\n\n');
  await fs.writeFile('./styles.css', output, 'utf-8');
  console.log('CSS build complete: styles.css (minimal - for Tailwind users)');
}

async function buildFullCSS() {
  // Run Tailwind CLI to generate full CSS with all utilities
  execSync('npx @tailwindcss/cli -i ./src/styles/tailwind.css -o ./styles.full.css --minify', {
    stdio: 'inherit',
  });
  console.log('CSS build complete: styles.full.css (full - for non-Tailwind users)');
}

async function buildCSS() {
  await buildSafelist();
  await Promise.all([buildMinimalCSS(), buildFullCSS()]);
}

async function watchCSS() {
  const { watch } = await import('node:fs');

  let timer = null;
  const rebuild = () => {
    // Debounce rapid successive change events
    clearTimeout(timer);
    timer = setTimeout(() => {
      buildCSS().catch(err => console.error('CSS rebuild failed:', err));
    }, 100);
  };

  for (const dir of ['./src/components', './src/styles']) {
    watch(dir, { recursive: true }, (event, filename) => {
      if (filename?.endsWith('.css')) {
        console.log(`CSS change detected: ${filename}`);
        rebuild();
      }
    });
  }

  console.log('Watching for CSS changes...');
}

buildCSS()
  .then(() => {
    if (process.argv.includes('--watch')) {
      return watchCSS();
    }
  })
  .catch(err => {
    console.error('CSS build failed:', err);
    process.exit(1);
  });
